/* Aval service worker.
 *
 * Caches ONLY the static app shell: hashed build assets (/_next/static: JS, CSS,
 * fonts), icons and the offline page. Pages, RSC payloads, API responses and
 * media are never intercepted or stored, so no message, chat, contact or user
 * data ever lands in Cache Storage. Sign-out deletes every cache.
 *
 * Registered as /sw.js?v=<build id>&app=<app version>: each deploy (and each app
 * version) is a new worker with its own cache, and the previous one's cache is
 * deleted when it activates.
 */

const PARAMS = new URL(self.location.href).searchParams;
const VERSION = PARAMS.get("v") || "dev";
const APP_VERSION = PARAMS.get("app") || "0";
// Bumped with the icon set (src/lib/pwa-assets.ts ICON_VERSION): a new cache name,
// so nothing from before (old icons, old manifest) survives the update.
const CACHE_VERSION = "v3";
const SHELL = `aval-${APP_VERSION}-${CACHE_VERSION}-shell-${VERSION}`;
// In development the build assets aren't content-hashed, so nothing is cached.
const CACHING = VERSION !== "dev";
const OFFLINE_URL = "/offline.html";
const MANIFEST_URL = "/manifest.webmanifest";
// The icon set and logo (generated by `pnpm icons`), so they never come from an older cache.
const ICONS = {
  any192: "/icons/icon-192.v3.png",
  badge: "/icons/badge-72.v3.png",
};
const PRECACHE = [
  OFFLINE_URL,
  MANIFEST_URL,
  ICONS.any192,
  "/icons/icon-512.v3.png",
  "/icons/icon-maskable-512.v3.png",
  "/icons/apple-touch-icon.v3.png",
  "/icons/favicon-32.v3.png",
  "/favicon.ico?v3",
  ICONS.badge,
  "/icons/logo-256.webp",
  "/icons/logo-512.webp",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL);
      await cache.addAll(PRECACHE);
      // The page that registered this worker is already running this build, so
      // take over at once; older tabs recover via Next's hard reload on a stale chunk.
      await self.skipWaiting();
    })(),
  );
});

/** Delete other builds' caches. */
async function pruneOldCaches() {
  const keys = await caches.keys();
  await Promise.all(keys.filter((k) => k.startsWith("aval-") && k !== SHELL).map((k) => caches.delete(k)));
}

/** False once a newer build's worker has taken over (this one may still finish a few fetches). */
const isCurrent = () => self.registration.active?.scriptURL === self.location.href;

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      await pruneOldCaches();
      if (self.registration.navigationPreload) await self.registration.navigationPreload.enable();
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.origin && event.origin !== self.location.origin) return;
  if (event.data?.type === "CLEAR_CACHES") {
    event.waitUntil(caches.keys().then((keys) => Promise.all(keys.map((k) => caches.delete(k)))));
  }
});

const isShellAsset = (url) =>
  url.pathname.startsWith("/_next/static/") ||
  url.pathname.startsWith("/icons/") ||
  url.pathname.startsWith("/splash/") ||
  url.pathname === "/favicon.ico";

let pruned = false;

/** Cache-first for immutable build assets and icons. Only successful same-origin responses are stored. */
async function shellAsset(event) {
  const { request } = event;
  // The previous worker may have re-created its cache while handing over; sweep once more.
  if (!pruned && isCurrent()) {
    pruned = true;
    event.waitUntil(pruneOldCaches());
  }
  const hit = await caches.match(request, { cacheName: SHELL });
  if (hit) return hit;
  const res = await fetch(request);
  // A replaced worker stops writing, so it can't resurrect its old cache.
  if (res.ok && res.type === "basic" && isCurrent()) {
    const copy = res.clone();
    event.waitUntil(caches.open(SHELL).then((cache) => cache.put(request, copy)));
  }
  return res;
}

/** Pages always come from the network (they contain user data); offline → the static offline page. */
async function navigate(event) {
  try {
    const preload = await event.preloadResponse;
    return preload || (await fetch(event.request));
  } catch {
    return (await caches.match(OFFLINE_URL)) || Response.error();
  }
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(navigate(event));
    return;
  }
  if (CACHING && isShellAsset(url) && !request.headers.has("RSC")) {
    event.respondWith(shellAsset(event));
    return;
  }
  // The manifest: always the network (so an icon change is seen at once); the
  // precached copy only when offline.
  if (CACHING && url.pathname === MANIFEST_URL) {
    event.respondWith(fetch(request).catch(() => caches.match(MANIFEST_URL, { cacheName: SHELL }).then((r) => r || Response.error())));
    return;
  }
  // Everything else (API, media, RSC) goes straight to the network.
});

/* ───────────── Push ───────────── */

/** Is a visible, focused window already showing this chat? Then don't notify. */
async function chatIsOnScreen(chatId) {
  const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  return windows.some((w) => w.focused && w.visibilityState === "visible" && chatId && new URL(w.url).pathname === `/chats/${chatId}`);
}

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { title: "Aval", body: "You have a new notification", url: "/chats" };
  }
  event.waitUntil(
    (async () => {
      if (data.kind === "message" && (await chatIsOnScreen(data.chatId))) return;
      const actions = [];
      // Inline reply (Chromium); other browsers ignore unknown action types.
      if (data.reply && data.chatId) actions.push({ action: "reply", type: "text", title: "Reply", placeholder: "Message" });
      actions.push({ action: "open", title: "Open" });
      await self.registration.showNotification(data.title || "Aval", {
        body: data.body || "",
        tag: data.tag,
        renotify: Boolean(data.tag),
        icon: ICONS.any192,
        badge: ICONS.badge,
        data: { url: data.url || "/chats", chatId: data.chatId || null },
        actions,
      });
    })(),
  );
});

async function openUrl(url) {
  const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  const existing = windows.find((w) => new URL(w.url).origin === self.location.origin);
  if (existing) {
    await existing.focus();
    if ("navigate" in existing) return existing.navigate(url);
    return existing;
  }
  return self.clients.openWindow(url);
}

self.addEventListener("notificationclick", (event) => {
  const { url, chatId } = event.notification.data || {};
  event.notification.close();

  if (event.action === "reply" && chatId && event.reply) {
    // Same-origin request with the session cookie; the API checks auth, membership
    // and Origin exactly as for the app itself.
    event.waitUntil(
      fetch(`/api/chats/${chatId}/messages`, {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ clientId: crypto.randomUUID().replace(/-/g, ""), text: event.reply }),
      }).then((res) => {
        if (!res.ok) return openUrl(url || "/chats");
      }),
    );
    return;
  }
  event.waitUntil(openUrl(url || "/chats"));
});
